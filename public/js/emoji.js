/** Flache Liste: [{ char, terms, group }] */
const CATALOG = GROUPS.flatMap((group) =>
  group.emoji.map((entry) => {
    const parts = entry.split(' ');
    return { char: parts[0], terms: parts.slice(1), group: group.id };
  }),
);

export const emojiGroups = () => GROUPS.map((group) => ({
  id: group.id,
  emoji: CATALOG.filter((item) => item.group === group.id).map((item) => item.char),
}));

export const allEmoji = () => CATALOG.map((item) => item.char);

/**
 * Sucht nach Anfangsstücken der Suchwörter. "her" findet Herz, "heart"
 * ebenfalls - und wer ein Emoji direkt eintippt oder einfügt, findet es auch.
 */
export function searchEmoji(query) {
  const clean = String(query ?? '').trim().toLowerCase();
  if (!clean) return [];
  const direct = CATALOG.filter((item) => item.char === clean.trim());
  if (direct.length) return direct.map((item) => item.char);
  const starts = [];
  const contains = [];
  for (const item of CATALOG) {
    let rank = 0;
    for (const term of item.terms) {
      if (term.startsWith(clean)) { rank = 2; break; }
      if (term.includes(clean)) rank = Math.max(rank, 1);
    }
    if (rank === 2) starts.push(item.char);
    else if (rank === 1) contains.push(item.char);
  }
  return [...starts, ...contains];
}

/**
 * Ist das überhaupt ein Emoji? Für das Freitextfeld - damit niemand aus
 * Versehen einen ganzen Satz als Reaktion setzt.
 */
export function looksLikeEmoji(text) {
  const clean = String(text ?? '').trim();
  if (!clean) return false;
  // Höchstens ein paar Zeichen, und mindestens eines davon ein Bildzeichen.
  if ([...clean].length > 8) return false;
  return /\p{Extended_Pictographic}/u.test(clean);
}
